def encode(text,vocab):
    ids=[vocab['[CLS]']]+[vocab.get(c,vocab['[UNK]']) for c in text.lower() if not c.isspace()][:WORDS-2]+[vocab['[SEP]']]
    return ids+[0]*(WORDS-len(ids))
def language_rows(vocab,seed=81):
    rng=random.Random(seed);rows=[];seen=set()
    for i,nouns in enumerate(NOUNS):
        for n in nouns:
            for _ in range(55):
                s=rng.choice(VERBS)+n+rng.choice(ENDS)
                if s not in seen:rows.append((encode(s,vocab),i));seen.add(s)
    tests=[(s,encode(s,vocab),i) for i,phrases in enumerate(HELD) for s in phrases]
    return rows,tests
